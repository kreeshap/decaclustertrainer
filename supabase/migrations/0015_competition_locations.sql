-- Generic competition location structure for state/subdivision selection.
-- Additive and idempotent: Michigan is the first enabled beta state, but the
-- schema supports districts, regions, areas, and future annual conferences.

create table if not exists public.states (
  id bigint generated by default as identity primary key,
  code text not null unique check (code = upper(code) and length(code) = 2),
  name text not null,
  is_active boolean not null default false,
  subdivision_type text not null default 'district',
  subdivision_label text not null default 'District',
  subdivision_label_plural text not null default 'Districts',
  district_selection_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.deca_subdivisions (
  id text primary key,
  state_code text not null references public.states(code) on update cascade on delete restrict,
  type text not null check (type in ('district', 'region', 'area')),
  number integer not null check (number > 0),
  name text not null,
  display_name text not null,
  is_active boolean not null default true,
  season text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (state_code, type, number, season)
);

create table if not exists public.deca_conferences (
  id text primary key,
  season text not null,
  level text not null check (level in ('district', 'region', 'area', 'state', 'international')),
  state_code text not null references public.states(code) on update cascade on delete restrict,
  subdivision_id text references public.deca_subdivisions(id) on update cascade on delete set null,
  name text not null,
  start_date date,
  end_date date,
  venue text,
  city text,
  status text not null default 'tba' check (status in ('confirmed', 'tba', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles add column if not exists state_code text;
alter table public.profiles add column if not exists deca_subdivision_id text;
alter table public.profiles add column if not exists subdivision_status text not null default 'unknown';

alter table public.profiles drop constraint if exists profiles_state_code_fkey;
alter table public.profiles add constraint profiles_state_code_fkey
  foreign key (state_code) references public.states(code) on update cascade on delete set null;

alter table public.profiles drop constraint if exists profiles_deca_subdivision_id_fkey;
alter table public.profiles add constraint profiles_deca_subdivision_id_fkey
  foreign key (deca_subdivision_id) references public.deca_subdivisions(id) on update cascade on delete set null;

alter table public.profiles drop constraint if exists profiles_subdivision_status_check;
alter table public.profiles add constraint profiles_subdivision_status_check
  check (subdivision_status in ('user_selected', 'auto_detected', 'unknown'));

