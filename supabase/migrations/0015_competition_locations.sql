drop policy if exists states_read_active on public.states;
create policy states_read_active on public.states
  for select to authenticated using (is_active);

drop policy if exists states_deny_student_writes on public.states;
create policy states_deny_student_writes on public.states
  for all to authenticated using (false) with check (false);

drop policy if exists deca_subdivisions_read_active on public.deca_subdivisions;
create policy deca_subdivisions_read_active on public.deca_subdivisions
  for select to authenticated using (is_active);

drop policy if exists deca_subdivisions_deny_student_writes on public.deca_subdivisions;
create policy deca_subdivisions_deny_student_writes on public.deca_subdivisions
  for all to authenticated using (false) with check (false);

drop policy if exists deca_conferences_read_active on public.deca_conferences;
create policy deca_conferences_read_active on public.deca_conferences
  for select to authenticated using (status in ('confirmed', 'tba'));

drop policy if exists deca_conferences_deny_student_writes on public.deca_conferences;
create policy deca_conferences_deny_student_writes on public.deca_conferences
  for all to authenticated using (false) with check (false);

